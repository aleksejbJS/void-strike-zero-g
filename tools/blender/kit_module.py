# Writes the generated TypeScript kit module (BodyKitData) from render_kit.py's crops and atlas slots.
import json
import math

CHANNELS = (('head', 'head'), ('torso', 'torso'), ('pelvis', 'torso'), ('upperArm', 'arm'), ('forearm', 'arm'),
            ('hand', 'arm'), ('palm', 'arm'), ('thigh', 'leg'), ('shin', 'leg'), ('foot', 'leg'))


def write_module(path: str, crops: dict, slots: dict, *, frame, atlas, hip, neck, sole) -> None:
    scale = 19 / math.dist(hip, neck)   # rig units per frame pixel
    data = {'frame': frame, 'atlas': {'imagePath': atlas[0], 'size': atlas[1]}, 'hip': hip, 'neck': neck, 'parts': {}}
    for part, c in crops.items():
        fx, fy = slots[(part, 'fixed')]
        bx, by = c['box'][0], c['box'][1]

        def move(p):
            return [round(p[0] - bx + fx, 2), round(p[1] - by + fy, 2)]

        entry = {'polygon': c['hull'], 'origin': c['origin'],
                 'atlas': {'polygon': [move(p) for p in c['hull']], 'origin': move(c['origin'])},
                 'channel': next(channel for prefix, channel in CHANNELS if part.startswith(prefix))}
        if c['axisEnd']:
            entry['axisEnd'] = c['axisEnd']
            entry['atlas']['axisEnd'] = move(c['axisEnd'])
        if (part, 'paint') in slots:
            px, py = slots[(part, 'paint')]
            entry['paintOffset'] = [px - fx, py - fy]
        if part.startswith('foot'):
            # The drawn sole (outline included) is the lowest opaque row of the boot's silhouette
            rows = [i for i, row in enumerate(c['union']) if row.any()]
            bottom = c['box'][1] + rows[-1] + 1
            entry['supportHeight'] = round((bottom - c['origin'][1]) * scale, 3)
        data['parts'][part] = entry
    with open(path, 'w') as f:
        f.write('// GENERATED by tools/blender/render_kit.py from art/3d/atom-robot.blend. Do not edit by hand.\n')
        f.write("import type { BodyKitData } from '../kitTypes';\n\n")
        head = {k: v for k, v in data.items() if k != 'parts'}
        f.write('export const ROBOT_KIT: BodyKitData = {\n')
        for key, value in head.items():
            f.write(f'    {key}: {json.dumps(value)},\n')
        f.write('    parts: {\n')
        for part, entry in data['parts'].items():   # one line per part keeps diffs readable
            f.write(f'        {part}: {json.dumps(entry, separators=(",", ":"))},\n')
        f.write('    },\n};\n')
